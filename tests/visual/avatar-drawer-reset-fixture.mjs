import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const src=readFileSync(new URL('../../manager/web_app.py',import.meta.url),'utf8');
const start=src.indexOf('  async function loadAccountProfile(){');
const end=src.indexOf('  document.querySelectorAll("[data-account-tab]")',start);
assert(start>0&&end>start);
const ids=['profile-name','profile-email','profile-display-name','account-drawer-name','account-drawer-email','account-drawer-initial','profile-avatar-letter','profile-avatar-img','account-drawer-avatar-img'];
const els=Object.fromEntries(ids.map(id=>[id,{hidden:false,textContent:'',value:'',src:'',onload:null,onerror:null}]));
let hasAvatar=true;
const ctx={byId:id=>els[id],api:path=>path,fetch:async()=>({ok:true,json:async()=>({profile:{name:'Operador',email:'ops@example.com',has_avatar:hasAvatar}})}),Date};
runInNewContext(src.slice(start,end)+'\nglobalThis.runProfile=loadAccountProfile;',ctx,{timeout:1000});
await ctx.runProfile();
els['profile-avatar-img'].onload();els['account-drawer-avatar-img'].onload();
assert.equal(els['account-drawer-avatar-img'].hidden,false);assert.equal(els['account-drawer-initial'].hidden,true);
hasAvatar=false;await ctx.runProfile();
assert.equal(els['profile-avatar-img'].hidden,true);assert.equal(els['account-drawer-avatar-img'].hidden,true);assert.equal(els['profile-avatar-letter'].hidden,false);assert.equal(els['account-drawer-initial'].hidden,false);
assert.equal(els['account-drawer-avatar-img'].onload,null);assert.equal(els['profile-avatar-img'].onload,null);
console.log('ACCOUNT AVATAR REMOVAL RESETS PROFILE AND DRAWER IMAGES OK');
