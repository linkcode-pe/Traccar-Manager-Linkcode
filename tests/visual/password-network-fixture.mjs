import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const source=readFileSync(new URL('../../manager/web_app.py',import.meta.url),'utf8');
const start=source.indexOf('  byId("password-save").addEventListener("click",async()=>{');
const end=source.indexOf('\n  loadAccountProfile();',start);
assert(start>0&&end>start);
const nodes={'password-status':{textContent:''},'password-current':{value:'existing-password'},'password-new':{value:'new-password-123'},'password-confirm':{value:'new-password-123'}};
let callback, requests=0;
const c={byId:id=>id==='password-save'?{addEventListener:(_event,fn)=>callback=fn}:nodes[id],api:s=>s,fetch:async()=>{requests++;throw Error('network down')},alert:()=>{throw Error('must not alert')},location:{reload:()=>{throw Error('must not reload')}}};
runInNewContext(source.slice(start,end),c,{timeout:1000});
await callback();
assert.equal(requests,1);
assert.match(nodes['password-status'].textContent,/No se pudo conectar/);
console.log('ACCOUNT PASSWORD NETWORK FAILURE HANDLED OK');
nodes['password-confirm'].value='mismatch';requests=0;
await callback();
assert.equal(requests,0);
assert.match(nodes['password-status'].textContent,/no coinciden/);
console.log('ACCOUNT PASSWORD MISMATCH STOPS REQUEST OK');
