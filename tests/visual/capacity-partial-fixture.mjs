import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const source=readFileSync(new URL('../../manager/web_app.py',import.meta.url),'utf8');
const start=source.indexOf('  function renderCapacityCenter(p,d){');
const end=source.indexOf('\n  function renderOperationalHealth(',start);
assert(start>0&&end>start);
const el=()=>({textContent:'',children:[],style:{width:''},append(...children){this.children.push(...children)},appendChild(x){this.children.push(x)},replaceChildren(){this.children=[]}});
const c={capacityBreakdown:el(),capacityFree:el(),capacityAccounting:el(),document:{createElement:el},formatBytes:n=>`${n} bytes`};
runInNewContext(source.slice(start,end)+'\nthis.render=renderCapacityCenter;',c,{timeout:1000});
c.render({capacity:{disk_total_bytes:0,disk_used_bytes:100}},{disk_total_bytes:0});
assert.equal(c.capacityBreakdown.children.length,0);
assert.match(c.capacityAccounting.textContent,/no verificable/);
console.log('CAPACITY ZERO DISK TOTAL FAILS CLOSED OK');
c.render({capacity:{disk_total_bytes:1000,disk_used_bytes:200,mysql_files_bytes:50,binlogs_bytes:10}},{disk_total_bytes:1000});
assert.equal(c.capacityBreakdown.children.length,6);
assert.match(c.capacityFree.textContent,/800/);
console.log('CAPACITY VALID DISK TOTAL OK');
c.render({capacity:{disk_total_bytes:null,disk_used_bytes:100}},{disk_total_bytes:null});
assert.equal(c.capacityBreakdown.children.length,0);
assert.match(c.capacityFree.textContent,/No disponible/);
console.log('CAPACITY MISSING DISK TOTAL CLEARS STALE UI OK');
