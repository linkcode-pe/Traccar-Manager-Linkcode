import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const source=readFileSync(new URL('../../manager/web_app.py',import.meta.url),'utf8');
const start=source.indexOf('  async function loadAuditHistory(){');
const end=source.indexOf('\n  function renderCapacityCenter(',start);
assert(start>0&&end>start);
const el=()=>({textContent:'',className:'',children:[],replaceChildren(){this.children=[]},appendChild(x){this.children.push(x)},append(...xs){this.children.push(...xs)}});
const c={auditEvents:el(),auditCount:el(),document:{createElement:el},fetchApi:async()=>({ok:true,json:async()=>({events:[null,{event:'AUTH_LOGIN',result:'SUCCEEDED',timestamp_utc:'2026-10-08T00:00:00Z'},false,{}, {event:'AUTH_LOGOUT',result:'DENIED',reason_code:'SESSION'}]})})};
runInNewContext(source.slice(start,end)+'\nthis.load=loadAuditHistory;',c,{timeout:1000});
await c.load();
assert.equal(c.auditCount.textContent,'3 eventos');
assert.equal(c.auditEvents.children.length,3);
assert.equal(c.auditEvents.children[1].children[1].textContent,'Evento sin tipo');
assert.equal(c.auditEvents.children[1].children[2].textContent,'No verificable');
console.log('AUDIT MALFORMED EVENTS DO NOT BREAK HISTORY OK');
c.fetchApi=async()=>({ok:false});
await c.load();
assert.equal(c.auditCount.textContent,'No disponible');
assert.match(c.auditEvents.textContent,/No se pudo consultar/);
console.log('AUDIT FAILED REQUEST SHOWS UNAVAILABLE OK');
