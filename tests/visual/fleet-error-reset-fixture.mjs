import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const src=readFileSync(new URL('../../manager/web_app.py',import.meta.url),'utf8');
const start=src.indexOf('  function clearFleetSnapshot(){');
const end=src.indexOf('  async function loadServerStatus(){',start);
assert(start>0&&end>start);
const ids=['devicesTotal','devicesEnabled','devicesDisabled','fleetTotal','fleetEnabled','fleetDisabled','fleetStale','fleetStateOnline','fleetStateRecent','fleetStateDay','fleetStateStale','fleetLive','fleetRecent','fleetDay','fleetEnabledBase','fleetLivePercent','fleetActive24','fleetHealth','fleetHealthDetail','fleetHealthCard','devicesObserved'];
const ctx=Object.fromEntries(ids.map(id=>[id,{textContent:'STALE',className:'stale'}]));
ctx.fleetLiveMeter={firstElementChild:{style:{width:'78%'}}};ctx.fleetActiveMeter={firstElementChild:{style:{width:'82%'}}};
runInNewContext(src.slice(start,end)+'\nclearFleetSnapshot();',ctx,{timeout:1000});
for(const id of ids.filter(id=>id!=='fleetHealthCard'))assert.notEqual(ctx[id].textContent,'STALE',`${id} remained stale`);
assert.notEqual(ctx.fleetHealthCard.className,'stale');
assert.equal(ctx.fleetLiveMeter.firstElementChild.style.width,'0%');assert.equal(ctx.fleetActiveMeter.firstElementChild.style.width,'0%');
assert.match(ctx.fleetHealth.textContent,/No verificable/);
const loader=src.slice(end,src.indexOf('  async function loadBoundaryHealth()',end));
assert(loader.includes('}else{clearFleetSnapshot();}'));
assert(loader.slice(loader.lastIndexOf('} catch(_e)')).includes('clearFleetSnapshot();'));
console.log('FLEET PARTIAL AND FAILED SNAPSHOT CLEARS ALL AGGREGATES OK');
